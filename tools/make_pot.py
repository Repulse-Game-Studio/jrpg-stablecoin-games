#!/usr/bin/env python3
"""Generate (or --check) godot/addons/scfg/translations/scfg.pot, the template for translating
the text the Godot addon shows to players.

    uv run python tools/make_pot.py           # write scfg.pot
    uv run python tools/make_pot.py --check   # exit 1 when scfg.pot is missing or out of date

The strings come from:
  - every `tr("...")` (or `tr('...')`) call with a literal string in addons/scfg/**.gd (comments
    are skipped; `tr(variable)` cannot be extracted and is ignored);
  - every `text`, `tooltip_text` and `placeholder_text` property in addons/scfg/**.tscn;
  - the core's player messages, which the screens translate when they show them: the checkout's
    MESSAGES (conformance/vectors/messages.json, the exact texts the controller hands out) and
    the restore screen's (the MESSAGES dictionary of addons/scfg/core/restore_flow.gd).

Entries are sorted by msgid, each listed once with every place it comes from (file names only,
no line numbers, so an edit that moves a string does not change the template).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GODOT = ROOT / "godot"
ADDON = GODOT / "addons" / "scfg"
POT = ADDON / "translations" / "scfg.pot"
MESSAGES_JSON = ROOT / "conformance" / "vectors" / "messages.json"
RESTORE_FLOW = ADDON / "core" / "restore_flow.gd"

_STRING = r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\''
TR_CALL = re.compile(r"\btr\(\s*(?:" + _STRING + r")\s*[,)]")
TSCN_TEXT = re.compile(r'^(?:text|tooltip_text|placeholder_text) = "((?:[^"\\]|\\.)*)"\s*$', re.M)
DICT_ENTRY = re.compile(r'^\s*"(\w+)"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,?\s*$')
# a key of a Dictionary entry: a string literal followed by ":"
DICT_KEY = re.compile(r'"(?:[^"\\\n]|\\.)*"\s*:')

HEADER = """\
# Text the Stablecoin for Games (SCFG) Godot addon shows to players.
# Generated by tools/make_pot.py from the addon's tr() calls and the core's player messages;
# do not edit. Translate it into a .po file (for example addons/scfg/translations/fr.po) and add
# that file under Project Settings > Localization > Translations.
msgid ""
msgstr ""
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8-bit\\n"
"""

_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "'": "'", "\\": "\\", "0": "\0"}


def unescape(s: str) -> str:
    """A GDScript (or .tscn) string literal's body as the string it denotes."""
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s):
            nxt = s[i + 1]
            if nxt == "u" and i + 5 < len(s):
                out.append(chr(int(s[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append(_ESCAPES.get(nxt, nxt))
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def po_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def _code(line: str) -> str:
    """`line` without its `#` comment (a `#` inside a string literal is kept)."""
    quote = None
    i = 0
    while i < len(line):
        ch = line[i]
        if quote:
            if ch == "\\":
                i += 1
            elif ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#":
            return line[:i]
        i += 1
    return line


class PotError(Exception):
    """A source the tool cannot read completely (the template would silently miss strings)."""


def restore_messages(text: str, name: str) -> list:
    """[(code, text)] of the `const MESSAGES := {...}` dictionary in restore_flow.gd's `text`, one
    `"code": "text",` entry per line. Raises PotError when the dictionary is missing or has an
    entry that is not on one such line (counted by its `"key":`), so none is dropped silently."""
    entries = []
    keys = 0
    in_messages = False
    for line in text.splitlines():
        if not in_messages:
            in_messages = line.startswith("const MESSAGES")
            continue
        if line.startswith("}"):
            break
        code = _code(line)
        keys += len(DICT_KEY.findall(code))
        m = DICT_ENTRY.match(code)
        if m:
            entries.append((m.group(1), unescape(m.group(2))))
    else:
        raise PotError(f"{name}: no `const MESSAGES := {{ ... }}` dictionary (with its closing "
                       "`}` at the start of a line) to read the restore screen's messages from")
    if keys != len(entries):
        raise PotError(f"{name}: read {len(entries)} of the {keys} MESSAGES entries; write each as "
                       '`"code": "text",` on one line (one string literal, no concatenation)')
    return entries


def _rel(path: Path) -> str:
    return path.relative_to(GODOT).as_posix() if path.is_relative_to(GODOT) else path.as_posix()


def collect() -> dict:
    """{msgid: [reference lines]}: `#: <file>` and `#. core message: <code>`."""
    entries: dict = {}

    def add(msgid: str, ref: str) -> None:
        refs = entries.setdefault(msgid, [])
        if ref not in refs:
            refs.append(ref)

    for path in sorted(ADDON.rglob("*.gd")):
        for line in path.read_text(encoding="utf-8").splitlines():
            for m in TR_CALL.finditer(_code(line)):
                body = m.group(1) if m.group(1) is not None else m.group(2)
                add(unescape(body), f"#: {_rel(path)}")
    for path in sorted(ADDON.rglob("*.tscn")):
        for m in TSCN_TEXT.finditer(path.read_text(encoding="utf-8")):
            if m.group(1):
                add(unescape(m.group(1)), f"#: {_rel(path)}")
    messages = json.loads(MESSAGES_JSON.read_text(encoding="utf-8"))["messages"]
    for code, text in sorted(messages.items()):
        add(text, f"#. core message: {code}")
    restore_text = RESTORE_FLOW.read_text(encoding="utf-8")
    for code, text in restore_messages(restore_text, _rel(RESTORE_FLOW)):
        add(text, f"#. core message: {code}")
    return entries


def render(entries: dict) -> str:
    blocks = [HEADER]
    for msgid in sorted(entries):
        refs = sorted(entries[msgid], key=lambda r: (not r.startswith("#."), r))
        blocks.append("\n".join(refs) + f'\nmsgid "{po_escape(msgid)}"\nmsgstr ""\n')
    return "\n".join(blocks)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if scfg.pot is missing or out of date")
    args = parser.parse_args(argv)
    try:
        text = render(collect())
    except PotError as err:
        print(f"make_pot: {err}")
        return 1
    if args.check:
        current = POT.read_text(encoding="utf-8") if POT.is_file() else None
        if current != text:
            why = "missing" if current is None else "out of date"
            print(f"make_pot: {_rel(POT)} is {why}; run `uv run python tools/make_pot.py`")
            return 1
        return 0
    POT.parent.mkdir(parents=True, exist_ok=True)
    with open(POT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {_rel(POT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
